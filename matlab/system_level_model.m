%% BIO-INSPIRED MICROGRID - SYSTEM-LEVEL SIMULINK DIAGRAM
% Reference architecture:
% 70 MW load | 11 kV AC bus | 10 feeders | 50 Hz
%
% PURPOSE:
% Build a system-level active-power signal-flow diagram.
%
% IMPORTANT:
% This is NOT a physical Simscape Electrical / EMT model.
% Gain blocks are interface placeholders with gain = 1.
% The model does not validate voltage, current, frequency,
% protection, inverter control, or electrical losses.
%
% BESS is an optional power-signal input.
% Input power signals are expressed in MW.
%
% Generated model:
% BioInspiredMicrogrid_SystemLevel_Template.slx

clear;
clc;

model = 'BioInspiredMicrogrid_SystemLevel_Template';

%% 1. CREATE MODEL

if bdIsLoaded(model)
    close_system(model, 0);
end

if exist([model '.slx'], 'file')
    delete([model '.slx']);
end

new_system(model);
open_system(model);

set_param(model, 'StopTime', '1');

%% 2. INPUT POWER SIGNALS
% Replace these input ports with actual PV/wind/BESS
% power profiles when integrating measured simulation data.

inputNames = {
    'PV_Array_P_MW_Input'
    'Wind_Turbine_P_MW_Input'
    'BESS_P_MW_Input_Optional'
    'GFL_DER_P_MW_Input'
    'Grid_P_MW_Input'
};

inputY = [65 155 245 405 505];

for k = 1:numel(inputNames)

    blk = [model '/' inputNames{k}];

    add_block('simulink/Sources/In1', blk, ...
        'Position', [30 inputY(k) 60 inputY(k)+20]);

    set_param(blk, 'Port', num2str(k));

end

%% 3. RENEWABLE SOURCE INTERFACES

add_block('simulink/Math Operations/Gain', ...
    [model '/PV_DC_DC_Interface'], ...
    'Gain', '1', ...
    'Position', [150 60 245 90]);

add_block('simulink/Math Operations/Gain', ...
    [model '/Wind_AC_DC_Rectifier'], ...
    'Gain', '1', ...
    'Position', [150 150 245 180]);

add_block('simulink/Math Operations/Gain', ...
    [model '/BESS_Bidirectional_DC_DC_Interface'], ...
    'Gain', '1', ...
    'Position', [150 240 265 270]);

%% 4. DC BUS POWER AGGREGATION

add_block('simulink/Math Operations/Sum', ...
    [model '/DC_Bus_ActivePower_Sum'], ...
    'Inputs', '+++', ...
    'Position', [325 130 355 220]);

%% 5. GRID-FORMING INVERTER AND TRANSFORMER

add_block('simulink/Math Operations/Gain', ...
    [model '/GFM_Inverter_Interface'], ...
    'Gain', '1', ...
    'Position', [420 165 520 195]);

add_block('simulink/Math Operations/Gain', ...
    [model '/Transformer_to_11kV_Interface'], ...
    'Gain', '1', ...
    'Position', [570 165 685 195]);

%% 6. GRID-FOLLOWING INVERTER

add_block('simulink/Math Operations/Gain', ...
    [model '/GFL_Inverter_Interface'], ...
    'Gain', '1', ...
    'Position', [550 395 650 425]);

%% 7. UTILITY GRID AND PCC

add_block('simulink/Math Operations/Gain', ...
    [model '/Utility_Grid_PCC_Interface'], ...
    'Gain', '1', ...
    'Position', [550 495 665 525]);

%% 8. LOCAL 11 kV AC BUS

add_block('simulink/Math Operations/Sum', ...
    [model '/11kV_AC_Bus_PCC_Power_Sum'], ...
    'Inputs', '+++', ...
    'Position', [745 295 775 395]);

%% 9. CONNECT RENEWABLE SOURCES TO THE DC BUS

add_line(model, ...
    'PV_Array_P_MW_Input/1', ...
    'PV_DC_DC_Interface/1', ...
    'autorouting', 'on');

add_line(model, ...
    'Wind_Turbine_P_MW_Input/1', ...
    'Wind_AC_DC_Rectifier/1', ...
    'autorouting', 'on');

add_line(model, ...
    'BESS_P_MW_Input_Optional/1', ...
    'BESS_Bidirectional_DC_DC_Interface/1', ...
    'autorouting', 'on');

add_line(model, ...
    'PV_DC_DC_Interface/1', ...
    'DC_Bus_ActivePower_Sum/1', ...
    'autorouting', 'on');

add_line(model, ...
    'Wind_AC_DC_Rectifier/1', ...
    'DC_Bus_ActivePower_Sum/2', ...
    'autorouting', 'on');

add_line(model, ...
    'BESS_Bidirectional_DC_DC_Interface/1', ...
    'DC_Bus_ActivePower_Sum/3', ...
    'autorouting', 'on');

%% 10. CONNECT GFM INVERTER TO THE AC BUS

add_line(model, ...
    'DC_Bus_ActivePower_Sum/1', ...
    'GFM_Inverter_Interface/1', ...
    'autorouting', 'on');

add_line(model, ...
    'GFM_Inverter_Interface/1', ...
    'Transformer_to_11kV_Interface/1', ...
    'autorouting', 'on');

add_line(model, ...
    'Transformer_to_11kV_Interface/1', ...
    '11kV_AC_Bus_PCC_Power_Sum/1', ...
    'autorouting', 'on');

%% 11. CONNECT GFL INVERTER TO THE AC BUS

add_line(model, ...
    'GFL_DER_P_MW_Input/1', ...
    'GFL_Inverter_Interface/1', ...
    'autorouting', 'on');

add_line(model, ...
    'GFL_Inverter_Interface/1', ...
    '11kV_AC_Bus_PCC_Power_Sum/2', ...
    'autorouting', 'on');

%% 12. CONNECT GRID THROUGH PCC

add_line(model, ...
    'Grid_P_MW_Input/1', ...
    'Utility_Grid_PCC_Interface/1', ...
    'autorouting', 'on');

add_line(model, ...
    'Utility_Grid_PCC_Interface/1', ...
    '11kV_AC_Bus_PCC_Power_Sum/3', ...
    'autorouting', 'on');

%% 13. DC BUS MEASUREMENT SCOPE

add_block('simulink/Sinks/Scope', ...
    [model '/Scope_DC_Bus_Power_MW'], ...
    'Position', [335 255 365 285]);

add_line(model, ...
    'DC_Bus_ActivePower_Sum/1', ...
    'Scope_DC_Bus_Power_MW/1', ...
    'autorouting', 'on');

%% 14. AC BUS MEASUREMENT SCOPE

add_block('simulink/Sinks/Scope', ...
    [model '/Scope_11kV_AC_Bus_Power_MW'], ...
    'Position', [805 425 835 455]);

add_line(model, ...
    '11kV_AC_Bus_PCC_Power_Sum/1', ...
    'Scope_11kV_AC_Bus_Power_MW/1', ...
    'autorouting', 'on');

%% 15. TEN FEEDERS AND TEN LOAD OUTPUTS
% Each feeder receives 10% of the AC-bus power signal.
% This represents equal signal allocation only; it does not
% model individual feeder impedances or physical load flow.

add_block('simulink/Signal Routing/Mux', ...
    [model '/Mux_Ten_Feeder_Powers'], ...
    'Inputs', '10', ...
    'Position', [1170 240 1200 450]);

for k = 1:10

    feederName = sprintf('Feeder_F%02d_10pct', k);
    loadName = sprintf('Load_F%02d_MW', k);

    y = 35 + (k-1)*57;

    %% Feeder block

    add_block('simulink/Math Operations/Gain', ...
        [model '/' feederName], ...
        'Gain', '0.1', ...
        'Position', [895 y 985 y+25]);

    %% Load output port

    add_block('simulink/Sinks/Out1', ...
        [model '/' loadName], ...
        'Position', [1040 y 1070 y+20]);

    set_param([model '/' loadName], ...
        'Port', num2str(k));

    %% AC bus to feeder

    add_line(model, ...
        '11kV_AC_Bus_PCC_Power_Sum/1', ...
        [feederName '/1'], ...
        'autorouting', 'on');

    %% Feeder to load output

    add_line(model, ...
        [feederName '/1'], ...
        [loadName '/1'], ...
        'autorouting', 'on');

    %% Feed measurement mux

    add_line(model, ...
        [feederName '/1'], ...
        sprintf('Mux_Ten_Feeder_Powers/%d', k), ...
        'autorouting', 'on');

end

%% 16. FEEDER POWER MEASUREMENT SCOPE

add_block('simulink/Sinks/Scope', ...
    [model '/Scope_Ten_Feeder_Powers_MW'], ...
    'Position', [1260 300 1290 330]);

add_line(model, ...
    'Mux_Ten_Feeder_Powers/1', ...
    'Scope_Ten_Feeder_Powers_MW/1', ...
    'autorouting', 'on');

%% 17. SAVE AND OPEN THE MODEL

save_system(model);

open_system(model);

fprintf('\n========================================\n');
fprintf('System-level model created successfully.\n');
fprintf('Model file: %s.slx\n', model);
fprintf('Number of feeders: 10\n');
fprintf('Reference load: 70 MW\n');
fprintf('Reference AC bus voltage: 11 kV\n');
fprintf('Frequency reference in project: 50 Hz\n');
fprintf('========================================\n');

fprintf(['\nIMPORTANT: This is an active-power signal-flow ' ...
    'template, not an EMT simulation.\n']);

fprintf(['Use actual model blocks and measurements before ' ...
    'claiming electrical simulation validation.\n']);